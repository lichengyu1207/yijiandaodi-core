class Command(BaseCommand):
    help = '清除旧信息流数据，导入105条新文章（7大栏目 x 15条）'

    def add_arguments(self, parser):
        parser.add_argument(
            '--clear-only',
            action='store_true',
            help='仅清除旧数据，不导入新数据',
        )

    def handle(self, *args, **options):
        if not options['clear_only']:
            self.stdout.write('=== 开始导入一鉴到底信息流（105条新内容） ===')

        self.clear_old_data()

        if options['clear_only']:
            self.stdout.write(self.style.SUCCESS('旧数据已清除'))
            return

        categories = self.create_categories()
        authors = self.create_authors()
        tags = self.create_tags()
        self.create_articles(categories, authors, tags)

        self.stdout.write(self.style.SUCCESS('=== 导入完成！105条文章 + 7个栏目 + 标签 + 作者 ==='))

    def clear_old_data(self):
        self.stdout.write('>>> 清除旧数据...')
        ArticleTag.objects.all().delete()
        Article.objects.all().delete()
        Tag.objects.all().delete()
        Category.objects.all().delete()
        FrontAuthor.objects.exclude(name__in=['老骇']).delete()
        self.stdout.write(self.style.WARNING('   已清除：ArticleTag / Article / Tag / Category / 非核心作者'))

    def create_categories(self):
        self.stdout.write('>>> 创建 7 个栏目...')
        cats = {}
        for cat_data in CATEGORY_DATA:
            cat, _ = Category.objects.update_or_create(
                slug=cat_data['slug'],
                defaults=cat_data,
            )
            cats[cat.slug] = cat
            self.stdout.write(f'   [OK] {cat.name} (id={cat.id})')
        return cats

    def create_authors(self):
        self.stdout.write('>>> 创建作者...')
        authors = {}
        for auth_data in AUTHOR_DATA:
            author, _ = FrontAuthor.objects.update_or_create(
                name=auth_data['name'],
                defaults=auth_data,
            )
            authors[author.name] = author
        return authors

    def create_tags(self):
        self.stdout.write('>>> 创建标签...')
        all_tags = {}
        for tag_list in TAG_POOL.values():
            for tag_name in tag_list:
                if tag_name not in all_tags:
                    tag, _ = Tag.objects.get_or_create(name=tag_name, slug=tag_name.lower().replace('/', '-'))
                    all_tags[tag_name] = tag
        self.stdout.write(f'   [OK] 共 {len(all_tags)} 个标签')
        return all_tags

    def create_articles(self, categories, authors, tag_pool):
        now = timezone.now()
        total = 0

        for xinfa_tag, title_list in TITLES.items():
            cat = categories.get(xinfa_tag.replace('_', '-'))
            zone_id = xinfa_tag.replace('_', '-')
            cat_tags = TAG_POOL.get(xinfa_tag, [])

            for idx, title in enumerate(title_list):
                article = Article(
                    title=title,
                    summary=self._generate_summary(xinfa_tag, idx),
                    content=self._generate_content(xinfa_tag, idx),
                    cover_image=f'/categories/{xinfa_tag}.jpg',
                    category=cat,
                    author=authors.get('老骇'),
                    status='published',
                    xinfa_tag=xinfa_tag,
                    zone_id=zone_id,
                    is_pinned=(idx < 3),
                    is_recommended=(random.random() < 0.25),
                    read_count=random.randint(500, 80000),
                    like_count=random.randint(20, 6000),
                    comment_count=random.randint(0, 300),
                    hook_line=random.choice(HOOK_LINES),
                    cta_text='立即体验安全执行层 ->',
                    cta_link='/chat',
                    published_at=now,
                )
                article.save()

                article_tags = random.sample(cat_tags, min(random.randint(2, 4), len(cat_tags)))
                for tag_name in article_tags:
                    tag_obj = tag_pool.get(tag_name)
                    if tag_obj:
                        ArticleTag.objects.get_or_create(article=article, tag=tag_obj)

                total += 1

        self.stdout.write(self.style.SUCCESS(f'   [OK] 已导入 {total} 篇文章'))


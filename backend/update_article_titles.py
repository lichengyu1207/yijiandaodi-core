def main():
    articles = list(Article.objects.all())
    total = len(articles)
    print(f'Total articles: {total}')

    updated = 0
    length_buckets = {'<20': 0, '20-30': 0, '30-40': 0, '40-45': 0, '>45': 0}
    
    category_titles = {}
    for cat_slug, titles in TITLES.items():
        shuffled = titles[:]
        random.shuffle(shuffled)
        category_titles[cat_slug] = shuffled

    counters = {slug: 0 for slug in TITLES.keys()}

    for article in articles:
        slug = article.category.slug if article.category else 'security-audit'
        
        if slug not in category_titles:
            slug = 'security-audit'
        
        pool = category_titles[slug]
        idx = counters[slug] % len(pool)
        new_title = pool[idx]
        counters[slug] += 1
        
        if new_title != article.title:
            article.title = new_title
            article.save(update_fields=['title'])
            updated += 1
        
        l = len(new_title)
        if l < 20:
            length_buckets['<20'] += 1
        elif l <= 30:
            length_buckets['20-30'] += 1
        elif l <= 40:
            length_buckets['30-40'] += 1
        elif l <= 45:
            length_buckets['40-45'] += 1
        else:
            length_buckets['>45'] += 1

    print(f'\nUpdated: {updated}/{total}')
    print(f'\nLength distribution:')
    for k, v in length_buckets.items():
        print(f'  {k}: {v}')
    print(f'\nPer category usage:')
    for slug, cnt in sorted(counters.items()):
        pool_size = len(TITLES.get(slug, []))
        print(f'  {slug}: {cnt} used (pool={pool_size})')

    print(f'\n--- Sample titles ---')
    for a in Article.objects.all().order_by('?')[:15]:
        print(f'  [{a.id}] ({len(a.title)}字) [{a.category.slug}] "{a.title}"')

if __name__ == '__main__':
    main()
